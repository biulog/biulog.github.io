    const fallbackLang = "zh";

    function detectLanguage() {
      return document.documentElement.dataset.homeLang || fallbackLang;
    }

    function imagePath(lang, index) {
      return `/assets/screens/${screenLangMap[lang]}/screen-${index}.webp?v=20260904`;
    }

    function updateShowcaseImages(lang) {
      const locale = screenLangMap[lang] || screenLangMap.zh;
      const localizedFamilyShots = {
        "family-home": 1,
        "family-handbook": 7,
        "family-pattern": 8,
        "family-vaccines": 5,
        "family-teeth": 6,
        "family-health": 4
      };
      document.querySelectorAll("[data-showcase-shot]").forEach((image) => {
        const shot = image.dataset.showcaseShot;
        const localizedIndex = localizedFamilyShots[shot];
        if ((lang === "de" || lang === "it") && localizedIndex) {
          image.src = imagePath(lang, localizedIndex);
        } else {
          const showcaseLocale = (lang === "de" || lang === "it") ? "en" : locale;
          image.src = `/assets/showcase/${showcaseLocale}/${shot}.webp?v=20260904`;
        }
        const localizedCaption = image.closest("article")?.querySelector("strong")?.textContent?.trim();
        if (localizedCaption) image.alt = localizedCaption;
      });
    }

    function setText(lang) {
      const data = copy[lang];
      document.documentElement.lang = data.htmlLang;
      document.title = data.title;
      document.querySelector('meta[name="description"]').setAttribute("content", data.description);
      document.querySelector('meta[property="og:title"]').setAttribute("content", data.title);
      document.querySelector('meta[property="og:description"]').setAttribute("content", data.description);
      document.querySelector('meta[name="twitter:title"]').setAttribute("content", data.title);
      document.querySelector('meta[name="twitter:description"]').setAttribute("content", data.description);
      document.querySelector('meta[name="keywords"]').setAttribute("content", data.keywords);

      document.querySelectorAll("[data-i18n]").forEach((node) => {
        const key = node.getAttribute("data-i18n");
        if (data[key]) node.textContent = data[key];
      });

      document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
        const key = node.getAttribute("data-i18n-aria");
        if (data[key]) node.setAttribute("aria-label", data[key]);
      });

      document.querySelectorAll("[data-lang]").forEach((button) => {
        button.classList.toggle("active", button.getAttribute("data-lang") === lang);
      });
    }

    function renderFeatures(lang) {
      const grid = document.getElementById("featureGrid");
      grid.innerHTML = "";
      copy[lang].features.forEach(([title, body], index) => {
        const article = document.createElement("article");
        article.className = "feature";
        article.innerHTML = `
          <div class="mark">${String(index + 1).padStart(2, "0")}</div>
          <h3></h3>
          <p></p>
        `;
        article.querySelector("h3").textContent = title;
        article.querySelector("p").textContent = body;
        grid.appendChild(article);
      });
    }

    function renderScreens(lang) {
      document.querySelectorAll("[data-shot-index]").forEach((image) => {
        const index = Number(image.getAttribute("data-shot-index"));
        image.src = imagePath(lang, index);
        image.alt = `BiuLog screenshot ${index}`;
      });

      const gallery = document.getElementById("screenGallery");
      gallery.innerHTML = "";
      copy[lang].shots.forEach(([title, body], index) => {
        const card = document.createElement("article");
        card.className = "shot-card";

        const caption = document.createElement("div");
        caption.className = "shot-caption";
        const strong = document.createElement("strong");
        strong.textContent = title;
        const span = document.createElement("span");
        span.textContent = body;
        caption.append(strong, span);
        card.appendChild(caption);

        const image = document.createElement("img");
        image.src = imagePath(lang, index + 1);
        image.alt = title;
        image.loading = "lazy";
        image.decoding = "async";
        card.appendChild(image);

        gallery.appendChild(card);
      });
    }

    function renderNotes(lang) {
      const notes = document.getElementById("notes");
      notes.innerHTML = "";
      copy[lang].notes.forEach(([title, body]) => {
        const article = document.createElement("article");
        article.className = "note";
        const strong = document.createElement("strong");
        strong.textContent = title;
        const p = document.createElement("p");
        p.textContent = body;
        article.append(strong, p);
        notes.appendChild(article);
      });
    }

    function renderPro(lang) {
      const list = document.getElementById("proList");
      list.innerHTML = "";
      copy[lang].proItems.forEach((item) => {
        const li = document.createElement("li");
        li.textContent = item;
        list.appendChild(li);
      });
    }

    function updateStoreLinks(lang) {
      const appStoreUrl = appStoreUrls[lang] || appStoreUrls.zh;
      const googlePlayUrl = googlePlayUrls[lang] || googlePlayUrls.zh;
      document.querySelectorAll("[data-app-store-link]").forEach((link) => {
        link.href = appStoreUrl;
      });
      document.querySelectorAll("[data-google-play-link]").forEach((link) => {
        link.href = googlePlayUrl;
      });
    }

    function setLanguage(lang) {
      const next = copy[lang] ? lang : fallbackLang;
      try { localStorage.setItem("biulog-site-lang", next); } catch (_) { /* Locale still works for this page. */ }
      setText(next);
      renderFeatures(next);
      renderScreens(next);
      renderNotes(next);
      renderPro(next);
      updateStoreLinks(next);
      updateShowcaseImages(next);
      document.dispatchEvent(new CustomEvent("biulog:language", { detail: { lang: next } }));

    }


    setLanguage(detectLanguage());
